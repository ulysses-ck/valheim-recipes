export function maxBiome(values, fallback = DEFAULT_BIOME) {
  let best = null
  let bestRank = -1
  for (const value of values) {
    if (!value || BIOME_RANK[value] === undefined) continue
    const rank = BIOME_RANK[value]
    if (rank > bestRank) {
      best = value
      bestRank = rank
    }
  }
  return best ?? fallback
}

export function biomeOfMaterial(itemId) {
  return MATERIAL_BIOMES[itemId] ?? null
}

export function biomeFromTraderUnlock(unlock, unlockHref) {
  const key = unlockHref.match(/\/global-key\/([^/?#]+)/)?.[1] ?? null
  if (key && TRADER_UNLOCK_BIOMES[key]) {
    return { biome: TRADER_UNLOCK_BIOMES[key], key, known: true }
  }
  if (!key && unlock?.trim().toLowerCase() === 'available immediately') {
    return { biome: DEFAULT_BIOME, key: null, known: true }
  }
  return { biome: DEFAULT_BIOME, key, known: false }
}
